/**
 * Two jobs, both run before `dev` and `build`:
 *
 *  1. Copy the compiled registry (registry/public/r) into this app's public/r so
 *     the deployed site serves the registry JSON the CLI fetches.
 *  2. Sync the real component *sources* into registry-preview/ so the docs can
 *     mount the actual components in live previews — never a mock-up. Only
 *     self-contained items (no '@/…' cross-item imports) are synced; those drop
 *     into the docs app unchanged. Items with registry dependencies are skipped
 *     for now (the preview pilot doesn't cover them yet).
 */
import { access, cp, mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));

// ── 1. registry JSON ───────────────────────────────────────────────────────
const src = join(here, '..', '..', '..', 'registry', 'public', 'r');
const dest = join(here, '..', 'public', 'r');

try {
  await access(src);
  await rm(dest, { recursive: true, force: true });
  await mkdir(dest, { recursive: true });
  await cp(src, dest, { recursive: true });
  console.log(`[copy-registry] copied registry into ${dest}`);
} catch {
  console.warn(
    '[copy-registry] registry/public/r not found — run `pnpm registry:build` first. Skipping.',
  );
}

// ── 2. real component sources for live previews ──────────────────────────────
const itemsDir = join(here, '..', '..', '..', 'registry', 'items');
const previewDir = join(here, '..', 'registry-preview');

await rm(previewDir, { recursive: true, force: true });
await mkdir(previewDir, { recursive: true });

const items = await readdir(itemsDir, { withFileTypes: true });
let synced = 0;
const skipped = [];
for (const entry of items) {
  if (!entry.isDirectory()) continue;
  const filesDir = join(itemsDir, entry.name, 'files');
  let files;
  try {
    files = await readdir(filesDir);
  } catch {
    continue; // item has no files/ dir
  }
  for (const file of files) {
    if (!file.endsWith('.tsx')) continue; // components only, skip .ts libs/css
    const source = await readFile(join(filesDir, file), 'utf8');
    // Self-contained = no cross-item import. Those resolve cleanly when dropped
    // into the docs app; cross-dep items need their deps wired up first.
    if (source.includes("from '@/")) {
      skipped.push(entry.name);
      continue;
    }
    // These are generated mirrors, typechecked + axe-tested in the registry
    // package against its own config. Skip type-checking them here: the docs app
    // uses stricter options and newer React types, which flag upstream code we
    // don't own. Runtime behaviour is unchanged.
    const banner = `// @ts-nocheck\n// AUTO-GENERATED by scripts/copy-registry.mjs — do not edit. Source of truth:\n// registry/items/${entry.name}/files/${file}\n`;
    await writeFile(join(previewDir, basename(file)), `${banner}${source}`);
    synced++;
  }
}
const skipNote = skipped.length ? ` (skipped cross-dep: ${[...new Set(skipped)].join(', ')})` : '';
console.log(`[copy-registry] synced ${synced} component source(s) into ${previewDir}${skipNote}`);
