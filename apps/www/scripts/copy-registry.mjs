/**
 * Two jobs, both run before `dev` and `build`:
 *
 *  1. Copy the compiled registry (registry/public/r) into this app's public/r so
 *     the deployed site serves the registry JSON the CLI fetches.
 *  2. Sync the real component *sources* into registry-preview/ so the docs can
 *     mount the actual components in live previews — never a mock-up.
 *
 *     The sync is dependency-aware: a component may import a sibling item via the
 *     `@/lib/…`, `@/components/…` or `@/hooks/…` aliases (e.g. data-table pulls in
 *     state-boundary, which pulls in the async-state lib). We flatten every source
 *     into registry-preview/ by basename and rewrite those cross-item imports to
 *     relative `./…` paths, so the whole dependency tree resolves in place. An item
 *     is only emitted once every cross-item import it needs is also present; the
 *     rare unsatisfiable one is skipped and logged.
 */
import { access, cp, mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));

// ── 1. registry JSON ───────────────────────────────────────────────────────
const src = join(here, '..', '..', '..', 'registry', 'public', 'r');
const dest = join(here, '..', 'public', 'r');

try {
  await access(src);
  await rm(dest, { recursive: true, force: true });
  await mkdir(dest, { recursive: true });
  await cp(src, dest, { recursive: true });
  console.log(`[copy-registry] copied registry into ${dest}`);
} catch {
  console.warn(
    '[copy-registry] registry/public/r not found — run `pnpm registry:build` first. Skipping.',
  );
}

// ── 2. real component sources for live previews ──────────────────────────────
const itemsDir = join(here, '..', '..', '..', 'registry', 'items');
const previewDir = join(here, '..', 'registry-preview');

await rm(previewDir, { recursive: true, force: true });
await mkdir(previewDir, { recursive: true });

// Cross-item imports the flatten step understands. Everything lands in
// registry-preview/ by basename, so `@/lib/async-state` → `./async-state`, etc.
// `theme` is styling/config (theme.css + the Tailwind preset), mirrored into
// globals.css already and never mounted — leave it out of the preview universe.
const CROSS_IMPORT = /from (['"])@\/(?:lib|components|hooks)\/([^'"]+)\1/g;
const IGNORED_ITEMS = new Set(['theme']);

// Pass 1 — index every candidate source by basename. No two items share a
// basename (asserted by the registry build), so a flat map is unambiguous.
const modules = new Map(); // basename → { item, file, source }
const items = await readdir(itemsDir, { withFileTypes: true });
for (const entry of items) {
  if (!entry.isDirectory() || IGNORED_ITEMS.has(entry.name)) continue;
  const filesDir = join(itemsDir, entry.name, 'files');
  let files;
  try {
    files = await readdir(filesDir);
  } catch {
    continue; // item has no files/ dir
  }
  for (const file of files) {
    if (!file.endsWith('.ts') && !file.endsWith('.tsx')) continue; // sources only, skip .css
    const name = basename(file).replace(/\.tsx?$/, '');
    const source = await readFile(join(filesDir, file), 'utf8');
    modules.set(name, { item: entry.name, file, source });
  }
}

// Pass 2 — emit each source whose cross-item deps are all present, rewriting the
// `@/…` aliases to flat relative imports. These are generated mirrors, already
// typechecked + axe-tested in the registry package against its own config; skip
// type-checking them here (the docs app uses stricter options and newer React
// types that flag upstream code we don't own). Runtime behaviour is unchanged.
let synced = 0;
const skipped = [];
for (const { item, file, source } of modules.values()) {
  const deps = [...source.matchAll(CROSS_IMPORT)].map((m) => m[2]);
  const missing = deps.filter((d) => !modules.has(d));
  if (missing.length) {
    skipped.push(`${item} (needs ${[...new Set(missing)].join(', ')})`);
    continue;
  }
  const rewritten = source.replace(CROSS_IMPORT, (_full, quote, dep) => `from ${quote}./${dep}${quote}`);
  const banner = `// @ts-nocheck\n// AUTO-GENERATED by scripts/copy-registry.mjs — do not edit. Source of truth:\n// registry/items/${item}/files/${file}\n`;
  await writeFile(join(previewDir, basename(file)), `${banner}${rewritten}`);
  synced++;
}
const skipNote = skipped.length ? ` (skipped unresolved: ${[...new Set(skipped)].join('; ')})` : '';
console.log(`[copy-registry] synced ${synced} component source(s) into ${previewDir}${skipNote}`);
